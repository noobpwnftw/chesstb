#!/usr/bin/env python3
"""Writes the prober as drop-in sources into OUT, everything in namespace chesstb:

  chesstb.h    the API (probe/probe.h and the headers it reaches); a host's
               macros of the same names are saved and restored around it
  chesstb.cpp  the same headers and every SOURCE, each file once

A host copies the two files and compiles chesstb.cpp with its own flags.
Includes of files outside the tree (system, lib/) stay where they stand, with
the namespace closed around them, so their #if conditions resolve on the host.

-t writes OUT/TOOL.cpp instead: TOOL, any SOURCEs and the headers they reach,
with a global main calling chesstb::main, to build next to chesstb.cpp. -I adds
a directory for quoted includes.

Usage: lib.py OUT SOURCE...
       lib.py -t [-I DIR]... OUT TOOL.cpp [SOURCE...]
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OURS = (os.path.join(ROOT, "src") + os.sep, os.path.join(ROOT, "tools") + os.sep)
INCLUDE = re.compile(r'\s*#\s*include\s*([<"])([^>"]+)[>"]')
DEFINE = re.compile(r'\s*#\s*define\s+(\w+)')
CONDITIONAL = re.compile(r'\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b')


def strip_comments(text):
    """The text without comments, string and char literals kept, line count kept."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == '"' or (c == "'" and not (i and (text[i - 1].isalnum() or text[i - 1] == "_"))):
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            out.append("\n" * text.count("\n", i, j))
            i = j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


class Inliner:
    def __init__(self, dirs):
        self.dirs = [os.path.join(ROOT, "src"), os.path.join(ROOT, "lib")] + dirs
        self.seen = set()
        self.macros = set()
        self.out = []
        self.inside = False
        self.directive = False

    def resolve(self, name, here):
        for d in [os.path.dirname(here)] + self.dirs:
            p = os.path.realpath(os.path.join(d, name))
            if os.path.isfile(p):
                return p
        sys.exit(f"lib.py: {here}: cannot find \"{name}\"")

    # The namespace closes only for an include from outside and reopens only for
    # code, so neighbouring includes share one gap. Each #if branch starts and
    # ends inside it, whichever branch the host's compiler takes.
    def outside(self, line):
        if self.inside:
            self.out.append("}\n")
            self.inside = False
        self.out.append(line)

    def line(self, line):
        s = line.strip()
        directive = self.directive or s.startswith("#")
        if CONDITIONAL.match(line) or not directive:
            if not self.inside:
                self.out.append("namespace chesstb {\n")
                self.inside = True
        self.directive = directive and s.endswith("\\")
        self.out.append(line)

    def file(self, path):
        if path in self.seen:
            return
        self.seen.add(path)
        for line in strip_comments(open(path).read()).splitlines():
            line = line.rstrip() + "\n"
            if line.strip() in ("", "#pragma once"):
                continue
            m = INCLUDE.match(line)
            if m and m.group(1) == "<":
                self.outside(line)
            elif m:
                p = self.resolve(m.group(2), path)
                if p.startswith(OURS):
                    self.file(p)
                else:
                    self.outside(line)
            else:
                d = DEFINE.match(line)
                if d and path.endswith(".h"):
                    self.macros.add(d.group(1))
                self.line(line)

    def text(self):
        return "".join(self.out + (["}\n"] if self.inside else []))


HEAD = "// Generated by tools/lib.py from the ChessTB sources.\n"


def main(argv):
    tool, dirs = False, []
    while argv and argv[0].startswith("-"):
        flag = argv.pop(0)
        if flag == "-t":
            tool = True
        elif flag.startswith("-I"):
            dirs.append(flag[2:] or argv.pop(0))
        else:
            sys.exit(f"lib.py: unknown option {flag}")
    out, files = argv[0], [os.path.realpath(f) for f in argv[1:]]
    os.makedirs(out, exist_ok=True)

    if tool:
        t = files[0]
        lib = Inliner(dirs)
        for f in files:
            lib.file(f)
        with open(os.path.join(out, os.path.basename(t)), "w") as f:
            f.write(HEAD + lib.text()
                    + "int main(int argc, char** argv) { return chesstb::main(argc, argv); }\n")
        return

    api = Inliner(dirs)
    api.file(os.path.join(ROOT, "src", "probe", "probe.h"))
    api.file(os.path.join(ROOT, "src", "chess", "notation.h"))
    macros = sorted(api.macros)
    with open(os.path.join(out, "chesstb.h"), "w") as f:
        f.write("#pragma once\n" + HEAD
                + "".join(f"#pragma push_macro(\"{m}\")\n#undef {m}\n" for m in macros)
                + api.text()
                + "".join(f"#undef {m}\n#pragma pop_macro(\"{m}\")\n" for m in macros))

    lib = Inliner(dirs)
    for s in files:
        lib.file(s)
    with open(os.path.join(out, "chesstb.cpp"), "w") as f:
        f.write(HEAD + lib.text())


if __name__ == "__main__":
    main(sys.argv[1:])
